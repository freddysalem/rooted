export interface Species {
  id: string;
  name: string;
  family: PlantFamily;
  light: LightNeed;
  /** How often it wants watering in fair weather. */
  waterEveryDays: number;
  /** Sow-to-harvest, used to drive the growth animation. */
  daysToHarvest: number;
  /** Typical height at maturity in a UK plot, cm. Gives a measured plant a scale to be read against. */
  matureHeightCm: number;
  /** Where it sits in the browsable catalogue. */
  category: PlantCategory;
  /** Month numbers, 1-12. */
  sowMonths: number[];
  harvestMonths: number[];
  /** 1 easy ... 3 fussy. */
  difficulty: number;
  tip: string;
  traits?: PlantTrait[];
}

export function difficultyLabel(difficulty: number): string {
  if (difficulty <= 1) return 'Easy';
  if (difficulty === 2) return 'Steady';
  return 'Needs attention';
}

